/* alias → 정본 역인덱스 + 자체 검증 (중복 alias 콘솔 경고) + 조회 함수 */
(function () {
  function key(s) {
    return String(s || '').toLowerCase()
      .replace(/\([^)]*\)/g, '')          // 괄호(함량% 등) 제거
      .replace(/\d+(\.\d+)?\s*%/g, '')    // 남은 % 표기 제거
      .replace(/[^\w가-힣]/g, '');        // 공백·기호 제거
  }
  const D = window.CM_INGR, lookup = {};
  Object.keys(D).forEach(function (canon) {
    [canon].concat(D[canon].a || []).forEach(function (s) {
      const k = key(s);
      if (!k) return;
      if (lookup[k] && lookup[k] !== canon) console.warn('[cm_ingrnorm] 표기 중복:', s, '→', canon, '↔', lookup[k]);
      lookup[k] = canon;
    });
  });
  window._cmIngrKey = key;
  /* 원재료 원문 → 정본. 사전에 없으면 원문 그대로(trim만) — 버리지 않는다 */
  window.cmIngrCanon = function (raw) {
    return lookup[key(raw)] || String(raw || '').trim();
  };
  /* 원재료 원문 → {raw, canon, fam, form, unspec, guess}
     사전에 있으면 그대로, 없으면 계열·형태 키워드로 추정(guess:true), 그래도 없으면 fam:null */
  window.cmIngrInfo = function (raw) {
    const r = String(raw || '').trim();
    const c = lookup[key(r)];
    if (c) { const e = D[c]; return {raw: r, canon: c, fam: e.f, form: e.t, unspec: !!e.u, guess: false}; }
    const k = key(r);
    const fh = window.CM_INGR_FAM_HINTS.find(function (h) { return k.indexOf(key(h[0])) !== -1; });
    if (!fh) return {raw: r, canon: r, fam: null, form: null, unspec: false, guess: false};
    const th = window.CM_INGR_FORM_HINTS.find(function (h) { return k.indexOf(key(h[0])) !== -1; });
    const unspec = ["가금류", "어류"].indexOf(fh[1]) !== -1;
    return {raw: r, canon: r, fam: fh[1], form: th ? th[1] : '고기', unspec: unspec, guess: true};
  };
})();
